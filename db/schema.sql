CREATE EXTENSION IF NOT EXISTS postgis;

CREATE TABLE IF NOT EXISTS settlements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    district TEXT NOT NULL,
    location GEOGRAPHY(Point, 4326) NOT NULL,
    population INTEGER NOT NULL CHECK (population >= 0),
    vulnerability_index NUMERIC(5, 2) NOT NULL DEFAULT 0 CHECK (vulnerability_index BETWEEN 0 AND 100),
    risk_score NUMERIC(5, 2) NOT NULL DEFAULT 0 CHECK (risk_score BETWEEN 0 AND 100),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (name, district)
);

CREATE INDEX IF NOT EXISTS settlements_location_gix ON settlements USING GIST (location);

CREATE TABLE IF NOT EXISTS hazard_factors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_id BIGINT NOT NULL REFERENCES settlements(id) ON DELETE CASCADE,
    factor_key TEXT NOT NULL,
    label TEXT NOT NULL,
    raw_value NUMERIC NOT NULL,
    risk_score NUMERIC(5, 2) NOT NULL CHECK (risk_score BETWEEN 0 AND 100),
    UNIQUE (settlement_id, factor_key)
);

CREATE TABLE IF NOT EXISTS candidate_sites (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_id BIGINT NOT NULL REFERENCES settlements(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    location GEOGRAPHY(Point, 4326) NOT NULL,
    hand_m NUMERIC NOT NULL DEFAULT 0,
    area_m2 NUMERIC NOT NULL CHECK (area_m2 >= 0),
    road_distance_km NUMERIC NOT NULL DEFAULT 0 CHECK (road_distance_km >= 0),
    m2_per_person NUMERIC NOT NULL DEFAULT 100 CHECK (m2_per_person > 0),
    suitability_score NUMERIC(5, 2) NOT NULL DEFAULT 0 CHECK (suitability_score BETWEEN 0 AND 100),
    capacity INTEGER NOT NULL DEFAULT 0 CHECK (capacity >= 0),
    UNIQUE (settlement_id, name)
);

CREATE INDEX IF NOT EXISTS candidate_sites_location_gix ON candidate_sites USING GIST (location);

CREATE TABLE IF NOT EXISTS hazard_zones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    properties JSONB NOT NULL DEFAULT '{}'::jsonb,
    geom geometry(MultiPolygon, 4326) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS hazard_zones_geom_gix ON hazard_zones USING GIST (geom);

CREATE TABLE IF NOT EXISTS decisions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_id BIGINT NOT NULL REFERENCES settlements(id),
    action TEXT NOT NULL CHECK (action IN ('Approved', 'Rejected')),
    actor TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    settlement_id BIGINT NOT NULL REFERENCES settlements(id),
    decision_id BIGINT REFERENCES decisions(id),
    action TEXT NOT NULL,
    actor TEXT NOT NULL,
    details JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS audit_log_created_at_idx ON audit_log (created_at DESC);
CREATE INDEX IF NOT EXISTS audit_log_settlement_idx ON audit_log (settlement_id, created_at DESC);
